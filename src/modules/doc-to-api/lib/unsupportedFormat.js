// 지원하지 않는 파일 형식에 대한 안내 문구 (순수 모듈).
//
// ⚠ 왜 안내인가: .hwp 파싱은 후순위다(2026-09-28 사용자 확정). npm 생태계가 죽어 있고
//    (hwp.js 0.0.3/2022, node-hwp alpha/2022), 바이너리에서 **표 구조를 복원하는 것**이
//    진짜 작업인데 시나리오 정의서는 표가 본체라 표 없이는 쓸모가 없다.
//    한글에서 PDF·docx로 저장하는 우회로는 30초이고 표가 보존된다.

const GUIDES = {
  hwp: '한글 파일은 지원하지 않습니다. 한글에서 PDF 또는 워드(.docx)로 저장해 올려주세요.',
  hwpx: '한글 파일은 지원하지 않습니다. 한글에서 PDF 또는 워드(.docx)로 저장해 올려주세요.',
  doc: '구 워드 형식(.doc)은 지원하지 않습니다. 워드에서 .docx로 저장해 올려주세요.',
  ppt: '파워포인트는 지원하지 않습니다. PDF로 저장해 올려주세요.',
  pptx: '파워포인트는 지원하지 않습니다. PDF로 저장해 올려주세요.',
}

/** 확장자에 맞는 안내 문구. 모르는 확장자는 기존 문구를 그대로 쓴다. */
export function unsupportedFormatMessage(ext) {
  const key = String(ext ?? '').toLowerCase()
  return GUIDES[key] ?? `지원하지 않는 파일 형식입니다: .${key}`
}
